export type TextSegment =
  | { kind: 'text', value: string }
  | { kind: 'emoticon', value: string }

/**
 * 把消息文本切分为普通文本段与表情段。
 * 已知表情名映射为对应 emoji；未知标记按原文本保留。
 */
export function splitEmoticonSegments(text: string): TextSegment[] {
  const segments: TextSegment[] = []
  let cursor = 0
  for (const match of text.matchAll(EMOTICON_PATTERN)) {
    const index = match.index ?? 0
    const name = match[1]
    const emoji = EMOTICON_MAP[name]
    if (!emoji)
      continue
    if (index > cursor)
      segments.push({ kind: 'text', value: text.slice(cursor, index) })
    segments.push({ kind: 'emoticon', value: emoji })
    cursor = index + match[0].length
  }
  if (cursor < text.length)
    segments.push({ kind: 'text', value: text.slice(cursor) })
  return segments
}
